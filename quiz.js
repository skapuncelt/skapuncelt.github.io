// 25問からランダムに10問を選ぶ
const selectedQuestions = [...quizQuestions]
    .sort(() => Math.random() - 0.5)
    .slice(0, 10);


// 現在の問題番号
let currentQuestion = 0;


// 正解数
let score = 0;


// クイズを表示する場所
const quizElement = document.getElementById("quiz");


// 問題を表示する
function showQuestion() {
    const question = selectedQuestions[currentQuestion];

    // 選択肢をランダムに並び替える
    const shuffledChoices = question.choices
        .map((choice, originalIndex) => ({
            choice: choice,
            originalIndex: originalIndex
        }))
        .sort(() => Math.random() - 0.5);

    quizElement.innerHTML = `
        <div class="quiz-question">

            <p class="quiz-progress">
                QUEST ${String(currentQuestion + 1).padStart(2, "0")} / 10
            </p>

            <h2>${question.question}</h2>

            <div class="quiz-choices">

                ${shuffledChoices.map((item, displayIndex) => `
                    <button
                        class="quiz-choice"
                        onclick="answerQuestion(${displayIndex}, ${item.originalIndex})"
                    >
                        ${item.choice}
                    </button>
                `).join("")}

            </div>

        </div>
    `;
}


// 答えを判定する
function answerQuestion(displayIndex, originalIndex) {
    const question = selectedQuestions[currentQuestion];
    const buttons = document.querySelectorAll(".quiz-choice");

    // 全ての選択肢を押せないようにする
    buttons.forEach(button => {
        button.disabled = true;
    });

    // 正解なら緑、不正解なら選んだ答えだけ赤
    if (originalIndex === question.answer) {
        buttons[displayIndex].classList.add("correct");
        score++;
    } else {
        buttons[displayIndex].classList.add("incorrect");
    }

    // 少し待って次の問題へ
    setTimeout(() => {
        currentQuestion++;

        if (currentQuestion < selectedQuestions.length) {
            showQuestion();
        } else {
            showResult();
        }
    }, 1000);
}


// 結果を表示する
function showResult() {

    // 10問すべて正解した場合
    if (score === 10) {
        showPerfectResult();
        return;
    }

    // 10問すべて正解ではない場合
    quizElement.innerHTML = `
        <div class="quiz-result">

            <p class="quiz-result-label">
                QUEST CLEAR
            </p>

            <h2>${score} / 10</h2>

            <p>
                お疲れさまでした！<br>
                SkaPunCeltクイズ終了です。
            </p>

        </div>
    `;
}


